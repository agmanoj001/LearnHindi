export function translateText(text) {
  const t = text.trim();
  if (HI[t]) return HI[t];
  for (const [re, out] of PATTERNS) if (re.test(t)) return t.replace(re, out);
  return null;
}

// Swap English text for Hindi inside `root`: text nodes, placeholders and aria-labels.
export function translateParent(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    // the language switch keeps "English" so English readers can always find their way back
    if (n.parentElement?.closest('.parent-lang')) continue;
    const hi = translateText(n.nodeValue);
    if (hi) {
      n.nodeValue = hi;
      n.parentElement?.setAttribute('lang', 'hi');
    }
  }
  for (const elm of root.querySelectorAll('[placeholder],[aria-label]')) {
    for (const attr of ['placeholder', 'aria-label']) {
      const v = elm.getAttribute(attr);
      const hi = v && translateText(v);
      if (hi) elm.setAttribute(attr, hi);
    }
  }
}

